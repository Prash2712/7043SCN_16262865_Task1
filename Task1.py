def make_prompt_prog(context, question):
    return (
        "You are given a financial context (text + table) and a question.\n"
        "Write a symbolic program using operators {divide,multiply,subtract,add,greater}.\n"
        "Use intermediate variables #0,#1,... produced in order.\n"
        "Return ONLY the program with comma-separated steps.\n\n"
        f"Context: {context}\n\n"
        f"Question: {question}\n\n"
        "Program:"
    )

def preprocess_prog(batch):
    prompts = [make_prompt_prog(c, q) for c, q in zip(batch["context"], batch["question"])]
    x = tokenizer(prompts, max_length=512, truncation=True)
    with tokenizer.as_target_tokenizer():
        y = tokenizer(batch["program"], max_length=128, truncation=True)
    x["labels"] = y["input_ids"]
    return x

