@torch.inference_mode()
def generate_with_conf(model, prompt, max_new_tokens=64):
    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=512).to(device)
    out = model.generate(
        **inputs,
        max_new_tokens=max_new_tokens,
        do_sample=False,
        num_beams=1,
        return_dict_in_generate=True,
        output_scores=True,
    )
    seq = out.sequences[0]
    text = tokenizer.decode(seq, skip_special_tokens=True).strip()

    scores = out.scores
    gen_token_ids = seq[-len(scores):]

    logps = []
    for logits, tok_id in zip(scores, gen_token_ids):
        logp = torch.log_softmax(logits[0], dim=-1)[tok_id].item()
        logps.append(logp)

    avg_logp = float(sum(logps) / max(1, len(logps)))
    return text, avg_logp

def squad_em_f1(pred, gold):
    p = norm_text(pred); g = norm_text(gold)
    em = 1 if p == g else 0
    p_toks, g_toks = p.split(), g.split()
    if len(p_toks) == 0 and len(g_toks) == 0: return em, 1.0
    if len(p_toks) == 0 or len(g_toks) == 0: return em, 0.0
    from collections import Counter
    common = Counter(p_toks) & Counter(g_toks)
    num_same = sum(common.values())
    if num_same == 0: return em, 0.0
    precision = num_same / len(p_toks)
    recall = num_same / len(g_toks)
    f1 = 2 * precision * recall / (precision + recall)
    return em, f1

