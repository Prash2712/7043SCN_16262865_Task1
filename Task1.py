def linearize_table(table):
    """Convert a FinQA table to compact text. Works for list-of-lists or pre-serialized strings."""
    if table is None:
        return ""
    if isinstance(table, str):
        return table
    lines = []
    for r_i, row in enumerate(table):
        if row is None:
            continue
        if isinstance(row, (list, tuple)):
            cells = [str(c) for c in row]
            lines.append(f"Row{r_i}: " + " | ".join(cells))
        else:
            lines.append(f"Row{r_i}: {row}")
    return "\n".join(lines)

