def squad_em_f1(pred, gold):
    # simple EM/F1 for single gold string (SQuAD v2 has multiple, but we're using first)
    p = norm_text(pred)
    g = norm_text(gold)

    em = 1 if p == g else 0

    # token F1
    p_toks = p.split()
    g_toks = g.split()
    if len(p_toks) == 0 and len(g_toks) == 0:
        return em, 1.0
    if len(p_toks) == 0 or len(g_toks) == 0:
        return em, 0.0
    common = {}
    for t in p_toks:
        common[t] = common.get(t, 0) + 1
    num_same = 0
    g_count = {}
    for t in g_toks:
        g_count[t] = g_count.get(t, 0) + 1
    for t in common:
        if t in g_count:
            num_same += min(common[t], g_count[t])
    if num_same == 0:
        return em, 0.0
    precision = num_same / len(p_toks)
    recall = num_same / len(g_toks)
    f1 = (2 * precision * recall) / (precision + recall)
    return em, f1

def compute_uhr(rows):
    # Unanswerable Hallucination Rate: on is_impossible examples, fraction not "No answer"
    unans = [r for r in rows if r["is_impossible"]]
    if not unans:
        return None
    hall = sum(1 for r in unans if norm_text(r["pred"]) != "no answer")
    return hall / len(unans)

def compute_ess(rows):
    # Evidence Support Score proxy
    supported = sum(1 for r in rows if context_contains_answer(r["context"], r["pred"]))
    return supported / len(rows) if rows else None

def compute_nhr(rows):
    # Number Hallucination Rate for FinQA: predicted numbers not present in context
    num_preds = 0
    hall = 0
    for r in rows:
        pred_nums = extract_numbers(r["pred"])
        if not pred_nums:
            continue
        num_preds += 1
        ctx_nums = set(extract_numbers(r["context"]))
        # hallucinated if ANY predicted number not in context
        if any(n not in ctx_nums for n in pred_nums):
            hall += 1
    return (hall / num_preds) if num_preds > 0 else None

