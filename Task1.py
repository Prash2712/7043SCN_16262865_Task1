import re, math

CONST_MAP = {
    "const_1": 1.0,
    "const_10": 10.0,
    "const_100": 100.0,
    "const_1000": 1000.0,
    "const_10000": 10000.0,
    "const_100000": 100000.0,
    "const_1000000": 1000000.0,
}

def to_number(token):
    if token is None:
        return None
    if isinstance(token, (int, float)):
        return float(token)

    s = str(token).strip()
    # remove trailing artifacts like "step 1"
    s = re.sub(r"\bstep\s*\d+\b.*$", "", s).strip()

    # constants
    if s in CONST_MAP:
        return CONST_MAP[s]

    s = s.replace(",", "")
    s = re.sub(r"[$£€]", "", s)

    # percentages like "23.6%" => 0.236  (IMPORTANT: treat as fraction!)
    if s.endswith("%"):
        try:
            return float(s[:-1]) / 100.0
        except:
            return None

    try:
        return float(s)
    except:
        return None

def safe_div(a, b):
    if a is None or b is None or b == 0:
        return None
    return a / b

def apply_op(op, args):
    op = op.lower()
    if op in ["add", "plus"]:
        return args[0] + args[1]
    if op in ["subtract", "sub", "minus"]:
        return args[0] - args[1]
    if op in ["multiply", "mul", "times"]:
        return args[0] * args[1]
    if op in ["divide", "div"]:
        return safe_div(args[0], args[1])

    # boolean comparisons (return "yes"/"no" to match dataset)
    if op == "greater":
        return "yes" if args[0] > args[1] else "no"
    if op == "less":
        return "yes" if args[0] < args[1] else "no"
    if op == "equal":
        return "yes" if args[0] == args[1] else "no"

    raise ValueError(f"Unsupported op: {op}")

def split_calls(program_text):
    """
    Split "divide(100, 100), divide(3.8, #0)" into ["divide(100, 100)", "divide(3.8, #0)"]
    without breaking commas inside parentheses.
    """
    s = program_text.strip()
    # remove trailing "step ..." if appended
    s = re.sub(r"\bstep\s*\d+\b.*$", "", s).strip()

    calls = []
    buf = []
    depth = 0
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth-1)

        if ch == "," and depth == 0:
            call = "".join(buf).strip()
            if call:
                calls.append(call)
            buf = []
        else:
            buf.append(ch)
    last = "".join(buf).strip()
    if last:
        calls.append(last)
    return calls

def parse_program_re(prog):
    """
    prog is raw_finqa ex["program_re"] string.
    Returns steps: [{"out":"#0","op":"divide","args":["100","100"]}, ...]
    """
    if prog is None:
        return None
    if isinstance(prog, list):
        prog = " ".join([str(x) for x in prog])
    if not isinstance(prog, str):
        return None

    calls = split_calls(prog)
    steps = []
    for i, call in enumerate(calls):
        m = re.match(r"\s*([A-Za-z_]+)\((.*)\)\s*$", call)
        if not m:
            return None
        op = m.group(1).strip()
        argstr = m.group(2).strip()
        args = [a.strip() for a in split_args(argstr)]
        steps.append({"out": f"#{i}", "op": op, "args": args})
    return steps

def split_args(argstr):
    """Split args inside a call; in this dataset it's simple, but keep robust."""
    # no nested parentheses expected inside args, but keep safe
    parts = []
    buf = []
    depth = 0
    for ch in argstr:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth-1)

        if ch == "," and depth == 0:
            part = "".join(buf).strip()
            if part:
                parts.append(part)
            buf = []
        else:
            buf.append(ch)
    last = "".join(buf).strip()
    if last:
        parts.append(last)
    return parts

def execute_program_re(prog):
    steps = parse_program_re(prog)
    if steps is None:
        return None, False, False  # value, parsed, executed
    env = {}
    last = None
    try:
        for s in steps:
            vals = []
            for a in s["args"]:
                if a in env:
                    vals.append(env[a])
                else:
                    vals.append(to_number(a))
            # if any numeric missing for numeric ops -> fail execute
            if s["op"].lower() not in ["greater","less","equal"] and any(v is None for v in vals):
                return None, True, False
            last = apply_op(s["op"], vals)
            env[s["out"]] = last
        return last, True, True
    except Exception:
        return None, True, False

def normalize_final_result(fr):
    s = str(fr).strip().lower()
    if s in ["yes","no"]:
        return s
    # keep percentage as float fraction for comparison, but also store % form
    n = to_number(s)
    return n if n is not None else s

def eval_gold_exec(split, n=500):
    total = 0
    parsed = 0
    executed = 0
    match = 0

    for i in range(min(n, len(split))):
        ex = split[i]
        gold = normalize_final_result(ex["final_result"])
        pred, p_ok, e_ok = execute_program_re(ex["program_re"])

        total += 1
        parsed += int(p_ok)
        executed += int(e_ok)

        if not e_ok:
            continue

        # compare
        if isinstance(gold, str):  # yes/no
            if isinstance(pred, str) and pred.lower() == gold:
                match += 1
        else:
            # numeric compare with tolerance
            if isinstance(pred, (int,float)):
                abs_err = abs(pred - gold)
                rel_err = abs_err / (abs(gold) + 1e-9)
                if abs_err <= 0.1 or rel_err <= 0.01:
                    match += 1

    return {
        "total": total,
        "parsed_rate": parsed/total,
        "executed_rate": executed/total,
        "gold_exec_match_rate": match/total
    }

