@torch.inference_mode()
def gen_program(model, context, question):
    prompt = make_prompt_prog(context, question)
    inp = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=512).to(device)
    out = model.generate(**inp, max_new_tokens=128, do_sample=False, num_beams=1)
    return tokenizer.decode(out[0], skip_special_tokens=True).strip()

def exec_accuracy(model, split, n=300):
    total = 0
    parsed = 0
    executed = 0
    correct = 0

    for i in range(min(n, len(split))):
        ex = split[i]
        ctx = build_finqa_context(ex)
        q = ex["question"]
        gold = normalize_final_result(ex["final_result"])

        pred_prog = gen_program(model, ctx, q)
        pred_val, p_ok, e_ok = execute_program_re(pred_prog)

        total += 1
        parsed += int(p_ok)
        executed += int(e_ok)

        if not e_ok:
            continue

        if isinstance(gold, str):  # yes/no
            if isinstance(pred_val, str) and pred_val.lower() == gold:
                correct += 1
        else:
            if isinstance(pred_val, (int,float)):
                abs_err = abs(pred_val - gold)
                rel_err = abs_err / (abs(gold) + 1e-9)
                if abs_err <= 0.1 or rel_err <= 0.01:
                    correct += 1

    return {
        "n": total,
        "parsed_rate": parsed/total,
        "executed_rate": executed/total,
        "exec_acc": correct/total,
        "exec_acc_given_executed": correct/executed if executed else None
    }

