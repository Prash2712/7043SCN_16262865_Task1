def clean_num_str(s):
    # remove currency symbols/commas/spaces
    s = s.strip()
    s = s.replace(",", "")
    s = re.sub(r"[$£€]", "", s)
    # convert percentages "12%" -> 12 (we will treat % specially if needed)
    return s

def to_float(x):
    try:
        return float(clean_num_str(x.replace("%","")))
    except:
        return None

