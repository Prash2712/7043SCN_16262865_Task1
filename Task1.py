@torch.inference_mode()
def generate_with_conf(prompt, max_new_tokens=64):
    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=512).to(device)

    # Generate
    gen_out = model.generate(
        **inputs,
        max_new_tokens=max_new_tokens,
        do_sample=False,
        num_beams=1,
        return_dict_in_generate=True,
        output_scores=True,
    )
    seq = gen_out.sequences[0]  # token ids (includes input for some models; for T5 it's decoder output ids)
    text = tokenizer.decode(seq, skip_special_tokens=True).strip()

    # Confidence: avg log-prob of generated tokens (decoder side)
    # scores: list over time steps, each is (vocab logits)
    scores = gen_out.scores
    # Align tokens: for seq2seq, sequences are decoder tokens; first token often is pad/start; we align by taking last len(scores) tokens
    gen_token_ids = seq[-len(scores):]

    logps = []
    for t, (logits, tok_id) in enumerate(zip(scores, gen_token_ids)):
        logprob = torch.log_softmax(logits[0], dim=-1)[tok_id].item()
        logps.append(logprob)

    avg_logp = float(sum(logps) / max(1, len(logps)))
    return text, avg_logp

